/

/* ---------- FACTURAS DE PROVEEDOR (cuentas por pagar) --------------------- */
CREATE OR REPLACE TRIGGER TRG_CXP_BIR
BEFORE INSERT ON CUENTA_POR_PAGAR FOR EACH ROW
WHEN (NEW.CXP_ESTADO IN ('PENDIENTE', 'PARCIAL'))
BEGIN
    PKG_CUENTAS.P_VALIDAR_LIMITE_PROVEEDOR(:NEW.PRV_ID, :NEW.CXP_SALDO);
END TRG_CXP_BIR;
/
CREATE OR REPLACE TRIGGER TRG_CXP_AIR
AFTER INSERT ON CUENTA_POR_PAGAR FOR EACH ROW
WHEN (NEW.CXP_ESTADO IN ('PENDIENTE', 'PARCIAL'))
BEGIN
    PKG_CUENTAS.P_AUMENTAR_SALDO_PROVEEDOR(:NEW.PRV_ID, :NEW.CXP_SALDO);
END TRG_CXP_AIR;
/
-- Cada linea de la factura del proveedor entra a la bodega central
CREATE OR REPLACE TRIGGER TRG_CXD_AIR
AFTER INSERT ON CXP_DETALLE FOR EACH ROW
BEGIN
    PKG_COMPRAS.P_RECIBIR_LINEA(:NEW.CXP_ID, :NEW.LOT_ID, :NEW.CXD_CANTIDAD, :NEW.CXD_PRECIO);
END TRG_CXD_AIR;
/
-- Devolucion a proveedor: sale de la bodega central
CREATE OR REPLACE TRIGGER TRG_DVD_AIR
AFTER INSERT ON DVP_DETALLE FOR EACH ROW
BEGIN
    PKG_INVENTARIO.P_MOVER_CENTRAL(:NEW.LOT_ID, -:NEW.DVD_CANTIDAD, 'DEVOLUCION_PROVEEDOR', 'DVP-' || :NEW.DVP_ID);
END TRG_DVD_AIR;
/
-- Devolucion aplicada contra una cuenta por pagar: baja lo que se debe
CREATE OR REPLACE TRIGGER TRG_DVP_AIUR
AFTER INSERT OR UPDATE OF DVP_ESTADO ON DEVOLUCION_PROVEEDOR FOR EACH ROW
WHEN (NEW.DVP_ESTADO = 'APLICADA' AND NEW.CXP_ID IS NOT NULL)
BEGIN
    IF INSERTING OR NVL(:OLD.DVP_ESTADO, 'X') <> 'APLICADA' THEN
        PKG_CUENTAS.P_APLICAR_DEVOLUCION_PRV(:NEW.CXP_ID, :NEW.DVP_MONTO);
    END IF;
END TRG_DVP_AIUR;
/

/* ---------- TRASLADOS (central -> sucursal) ------------------------------- */
CREATE OR REPLACE TRIGGER TRG_TRA_AIR
AFTER INSERT ON TRASLADO_INVENTARIO FOR EACH ROW
BEGIN
    PKG_INVENTARIO.P_MOVER_CENTRAL(:NEW.LOT_ID, -:NEW.TRA_CANTIDAD, 'TRASLADO_SALIDA', 'TRA-' || :NEW.TRA_ID);
    PKG_INVENTARIO.P_MOVER_SUCURSAL(:NEW.LOT_ID, :NEW.SUC_ID, :NEW.TRA_CANTIDAD, 'TRASLADO_ENTRADA', 'TRA-' || :NEW.TRA_ID);
END TRG_TRA_AIR;
/

/* ---------- HISTORIAL AUTOMATICO DE PRECIOS ------------------------------- */
CREATE OR REPLACE TRIGGER TRG_PRD_AUR
AFTER UPDATE OF PRD_PRECIO_COSTO ON PRODUCTO FOR EACH ROW
WHEN (NEW.PRD_PRECIO_COSTO <> OLD.PRD_PRECIO_COSTO)
BEGIN
    PKG_PRECIOS.P_REGISTRAR_CAMBIO_COSTO(:NEW.PRD_ID, :NEW.PRD_PRECIO_COSTO, :NEW.IMP_ID);
END TRG_PRD_AUR;
/
CREATE OR REPLACE TRIGGER TRG_PRN_AUR
AFTER UPDATE OF PRN_PORC_UTILIDAD ON PRODUCTO_NEGOCIO FOR EACH ROW
WHEN (NEW.PRN_PORC_UTILIDAD <> OLD.PRN_PORC_UTILIDAD)
BEGIN
    PKG_PRECIOS.P_REGISTRAR_CAMBIO_UTILIDAD(:NEW.PRD_ID, :NEW.NEG_ID, :NEW.PRN_PORC_UTILIDAD);
END TRG_PRN_AUR;
/

/* ---------- PADRON NACIONAL: datos basicos del cliente -------------------- */
CREATE OR REPLACE TRIGGER TRG_CLI_BIUR
BEFORE INSERT OR UPDATE OF CLI_CEDULA, CLI_TIPO_PERSONA ON CLIENTE FOR EACH ROW
WHEN (NEW.CLI_TIPO_PERSONA = 'NACIONAL')
DECLARE
    v_pad PADRON_NACIONAL%ROWTYPE;
BEGIN
    v_pad := PKG_PADRON.F_BUSCAR(:NEW.CLI_CEDULA);
    IF v_pad.PAD_ID IS NOT NULL THEN
        :NEW.CLI_PAD_ID    := v_pad.PAD_ID;
        :NEW.CLI_NOMBRE    := INITCAP(v_pad.PAD_NOMBRE);
        :NEW.CLI_APELLIDO1 := INITCAP(v_pad.PAD_APELLIDO1);
        :NEW.CLI_APELLIDO2 := INITCAP(v_pad.PAD_APELLIDO2);
        :NEW.CLI_SEXO      := v_pad.PAD_SEXO;
    END IF;
END TRG_CLI_BIUR;
/
