ALTER SESSION SET CURRENT_SCHEMA = SUM_ADMIN;

/* ---------- FACTURA ------------------------------------------------------- */
-- Define el estado inicial y valida el limite de credito si queda pendiente de pago
CREATE OR REPLACE TRIGGER TRG_FAC_BIR
BEFORE INSERT ON FACTURA FOR EACH ROW
BEGIN
    IF :NEW.FAC_ESTADO IS NULL THEN
        :NEW.FAC_ESTADO := CASE WHEN :NEW.FAC_TIPO = 'CREDITO' THEN 'PENDIENTE' ELSE 'CANCELADA' END;
    END IF;
    IF :NEW.FAC_ESTADO = 'PENDIENTE' THEN
        PKG_CUENTAS.P_VALIDAR_LIMITE_CLIENTE(:NEW.CLI_ID, :NEW.FAC_TOTAL);
    END IF;
END TRG_FAC_BIR;
/
-- Factura pendiente: crea la cuenta por cobrar y aumenta el saldo del cliente
CREATE OR REPLACE TRIGGER TRG_FAC_AIR
AFTER INSERT ON FACTURA FOR EACH ROW
WHEN (NEW.FAC_ESTADO = 'PENDIENTE')
BEGIN
    PKG_CUENTAS.P_REGISTRAR_CXC(:NEW.FAC_ID, :NEW.CLI_ID, :NEW.FAC_FECHA, :NEW.FAC_TOTAL);
END TRG_FAC_AIR;
/
-- Integridad: solo se permiten las transiciones de estado validas
CREATE OR REPLACE TRIGGER TRG_FAC_BUR
BEFORE UPDATE OF FAC_ESTADO ON FACTURA FOR EACH ROW
WHEN (OLD.FAC_ESTADO <> NEW.FAC_ESTADO)
BEGIN
    IF :OLD.FAC_ESTADO IN ('ANULADA', 'DEVUELTA')
       OR (:OLD.FAC_ESTADO = 'CANCELADA' AND :NEW.FAC_ESTADO = 'PENDIENTE') THEN
        PKG_ERRORES.P_REGISTRAR('TRG_FAC_BUR', 'TRANSICION', -20176,
            'Transicion invalida ' || :OLD.FAC_ESTADO || ' -> ' || :NEW.FAC_ESTADO, 'fac=' || :OLD.FAC_ID);
        RAISE_APPLICATION_ERROR(-20176, 'Transicion de estado invalida: ' ||
                                :OLD.FAC_ESTADO || ' -> ' || :NEW.FAC_ESTADO);
    END IF;
END TRG_FAC_BUR;
/
-- Factura anulada: el stock vuelve a la sucursal y la cuenta por cobrar se anula
CREATE OR REPLACE TRIGGER TRG_FAC_AUR
AFTER UPDATE OF FAC_ESTADO ON FACTURA FOR EACH ROW
WHEN (NEW.FAC_ESTADO = 'ANULADA' AND OLD.FAC_ESTADO IN ('PENDIENTE', 'CANCELADA'))
BEGIN
    PKG_INVENTARIO.P_REVERTIR_FACTURA(:NEW.FAC_ID, :NEW.SUC_ID);
    PKG_CUENTAS.P_ANULAR_CXC(:NEW.FAC_ID);
END TRG_FAC_AUR;
/

/* ---------- FAC_DETALLE / NOTAS DE CREDITO -------------------------------- */
-- Cada linea de producto descuenta el inventario de la sucursal donde se factura
CREATE OR REPLACE TRIGGER TRG_FCD_AIR
AFTER INSERT ON FAC_DETALLE FOR EACH ROW
WHEN (NEW.LOT_ID IS NOT NULL)
DECLARE
    v_suc FACTURA.SUC_ID%TYPE;
BEGIN
    SELECT SUC_ID INTO v_suc FROM FACTURA WHERE FAC_ID = :NEW.FAC_ID;
    PKG_INVENTARIO.P_MOVER_SUCURSAL(:NEW.LOT_ID, v_suc, -:NEW.FCD_CANTIDAD, 'VENTA', 'FAC-' || :NEW.FAC_ID);
END TRG_FCD_AIR;
/
-- Nota de credito: rebaja el saldo pendiente / marca la factura devuelta
CREATE OR REPLACE TRIGGER TRG_NTC_AIR
AFTER INSERT ON NOTA_CREDITO FOR EACH ROW
WHEN (NEW.NTC_ESTADO = 'APLICADA')
BEGIN
    PKG_CUENTAS.P_APLICAR_NOTA_CREDITO(:NEW.FAC_ID, :NEW.NTC_MONTO, :NEW.NTC_TIPO);
END TRG_NTC_AIR;
/
-- Devolucion de un cliente: el producto vuelve al inventario de la sucursal
CREATE OR REPLACE TRIGGER TRG_NTD_AIR
AFTER INSERT ON NTC_DETALLE FOR EACH ROW
DECLARE
    v_lot NUMBER;
    v_suc NUMBER;
BEGIN
    SELECT d.LOT_ID, f.SUC_ID INTO v_lot, v_suc
      FROM FAC_DETALLE d JOIN FACTURA f ON f.FAC_ID = d.FAC_ID
     WHERE d.FCD_ID = :NEW.FCD_ID;
    IF v_lot IS NOT NULL THEN                       -- los servicios no manejan inventario
        PKG_INVENTARIO.P_MOVER_SUCURSAL(v_lot, v_suc, :NEW.NTD_CANTIDAD, 'DEVOLUCION_CLIENTE', 'NTC-' || :NEW.NTC_ID);
    END IF;
END TRG_NTD_AIR;
/

/* ---------- ABONOS (cambio automatico de estado) -------------------------- */
