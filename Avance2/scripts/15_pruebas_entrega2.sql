/* ============================================================================
   ENTREGABLE #2 - PARTE A - 15_pruebas_entrega2.sql
   Pruebas funcionales de la Entrega 2 (ejecutar despues de 10 a 14).
   NOTIF_MODO queda en SIMULADO: los mensajes se ven en NOTIFICACION_LOG.
   ============================================================================ */
ALTER SESSION SET CURRENT_SCHEMA = SUM_ADMIN;
SET SERVEROUTPUT ON LINESIZE 200

-- 1) Promociones: factura con productos patrocinadores -> acciones automaticas
SELECT PRM_ID, PRM_NOMBRE, PRM_CANT_REQUERIDA, PRM_CANT_ACCIONES FROM PROMOCION;
SELECT PRM_ID, PRD_ID FROM PRM_PRODUCTO_PATROCINADOR ORDER BY PRM_ID;
DECLARE
    v_lin PKG_FACTURACION.t_lineas_fac; v_fac NUMBER;
BEGIN
    v_lin(1).lot_id := 1; v_lin(1).cantidad := 6;       -- ajuste el lote a un producto patrocinador de la consulta anterior
    PKG_FACTURACION.P_FACTURAR(2, 1, 2, 'CONTADO', v_lin, 1, NULL, v_fac);
END;
/
SELECT * FROM PROMOCION_CLIENTE ORDER BY PMC_ID DESC;
SELECT * FROM VW_ACCIONES_CLIENTE;

-- 2) Descuentos programados semanales
EXEC PKG_DESCUENTOS.P_APLICAR_PROGRAMADOS;
SELECT DSP_ID, DES_ID, LOT_ID, DSP_PORCENTAJE, DSP_ESTADO FROM DESCUENTO_PRODUCTO;

-- 3) Mercadeo semanal y vencidos
EXEC PKG_MERCADEO.P_REPORTE_SEMANAL;
EXEC PKG_MERCADEO.P_NOTIFICAR_VENCIDOS;

-- 4) Clientes premiados (forzado para la prueba)
EXEC PKG_PREMIOS.P_PREMIAR_MEJORES_CLIENTES('S');
SELECT CPR_POSICION, CLI_ID, CPR_TOTAL_COMPRADO, CPR_MONTO_ORDEN FROM CLIENTE_PREMIADO ORDER BY CPR_POSICION;

-- 5) Cierre diario
EXEC PKG_CIERRE.P_CIERRE_DIARIO(TRUNC(SYSDATE));
SELECT * FROM CIERRE_DIARIO ORDER BY CIE_ID DESC;
SELECT * FROM CIERRE_DIARIO_DETALLE ORDER BY CID_ID DESC;

-- 6) Notificaciones de credito: se baja el limite de un cliente para llegar al 85% (CK exige saldo <= limite)
UPDATE CLIENTE SET CLI_LIMITE_CREDITO = CEIL(CLI_SALDO_ACTUAL / 0.9) WHERE CLI_ID = 4;
UPDATE PROVEEDOR SET PRV_LIMITE_CREDITO = CEIL(PRV_SALDO_ACTUAL / 0.75) WHERE PRV_ID = 3;
COMMIT;
EXEC PKG_NOTIFICACIONES.P_EJECUTAR_TODAS;
SELECT NTL_TIPO, NTL_DESTINATARIOS, NTL_ASUNTO, NTL_ESTADO FROM NOTIFICACION_LOG ORDER BY NTL_ID DESC FETCH FIRST 10 ROWS ONLY;
SELECT NTL_MENSAJE FROM NOTIFICACION_LOG WHERE NTL_TIPO = 'MOROSOS' ORDER BY NTL_ID DESC FETCH FIRST 1 ROW ONLY;

-- 7) Auditoria y bitacoras
UPDATE CLIENTE SET CLI_PUESTO = 'Gerente de compras' WHERE CLI_ID = 5;
COMMIT;
SELECT AUD_TABLA, AUD_ACCION, AUD_REGISTRO, AUD_USUARIO, SUBSTR(AUD_DETALLE, 1, 100) DETALLE FROM AUDITORIA ORDER BY AUD_ID DESC FETCH FIRST 8 ROWS ONLY;
SELECT BCL_ACCION, BCL_FECHA, SUBSTR(BCL_DATOS_ANT, 1, 60) ANT FROM BIT_CLIENTE ORDER BY BCL_ID DESC FETCH FIRST 3 ROWS ONLY;
SELECT BFA_REGISTRO_ID, BFA_ACCION, SUBSTR(BFA_DATOS_NUE, 1, 80) NUE FROM BIT_FACTURACION ORDER BY BFA_ID DESC FETCH FIRST 3 ROWS ONLY;

-- 8) Procesos ejecutados y vistas materializadas
SELECT PRL_PROCESO, PRL_ESTADO, PRL_MENSAJE FROM PROCESO_LOG ORDER BY PRL_ID DESC FETCH FIRST 12 ROWS ONLY;
EXEC PKG_REPORTES.P_REFRESCAR_MV;
SELECT * FROM MV_VENTAS_MENSUALES;
