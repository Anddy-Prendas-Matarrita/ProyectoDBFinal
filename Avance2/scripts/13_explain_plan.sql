/* ============================================================================
   ENTREGABLE #2 - PARTE A - 13_explain_plan.sql
   Analisis con EXPLAIN PLAN de las consultas de los requerimientos funcionales.
   Para cada consulta se muestra costo (COST), operacion de acceso y el indice usado.
   COMO LEER EL RESULTADO: INDEX UNIQUE/RANGE SCAN = usa indice; TABLE ACCESS FULL = lee toda la
   tabla (aceptable en tablas pequenas o cuando se necesita la mayoria de las filas).
   Anote el COST y el indice de cada consulta en la tabla del manual tecnico.
   ============================================================================ */
ALTER SESSION SET CURRENT_SCHEMA = SUM_ADMIN;
SET LINESIZE 200 PAGESIZE 100
EXEC DBMS_STATS.GATHER_SCHEMA_STATS(ownname => 'SUM_ADMIN', cascade => TRUE);

-- Q1: clientes con 85% o mas del limite (notificacion a clientes y coordinador)
EXPLAIN PLAN SET STATEMENT_ID = 'Q1' FOR
SELECT CLI_ID, CLI_SALDO_ACTUAL, CLI_LIMITE_CREDITO FROM CLIENTE
 WHERE CLI_ESTADO = 'A' AND CLI_LIMITE_CREDITO > 0 AND CLI_SALDO_ACTUAL >= CLI_LIMITE_CREDITO * 85 / 100;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'Q1', 'BASIC +COST +PREDICATE'));

-- Q2: proveedores con 70% o mas del limite
EXPLAIN PLAN SET STATEMENT_ID = 'Q2' FOR
SELECT PRV_ID, PRV_SALDO_ACTUAL, PRV_LIMITE_CREDITO FROM PROVEEDOR
 WHERE PRV_ESTADO = 'A' AND PRV_LIMITE_CREDITO > 0 AND PRV_SALDO_ACTUAL >= PRV_LIMITE_CREDITO * 70 / 100;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'Q2', 'BASIC +COST +PREDICATE'));

-- Q3: clientes morosos (ultimo pago con mas de 30 dias)
EXPLAIN PLAN SET STATEMENT_ID = 'Q3' FOR
SELECT c.CLI_ID, c.CLI_SALDO_ACTUAL,
       (SELECT MAX(a.ABC_FECHA) FROM CXC_ABONO a JOIN CUENTA_POR_COBRAR x ON x.CXC_ID = a.CXC_ID WHERE x.CLI_ID = c.CLI_ID) ULT
  FROM CLIENTE c WHERE c.CLI_SALDO_ACTUAL > 0;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'Q3', 'BASIC +COST +PREDICATE'));

-- Q4: productos por vencer en 7 dias (usa IX_LOT_VENCIMIENTO)
EXPLAIN PLAN SET STATEMENT_ID = 'Q4' FOR
SELECT l.LOT_ID, l.LOT_FECHA_VENCIMIENTO FROM LOTE l
 WHERE l.LOT_FECHA_VENCIMIENTO BETWEEN TRUNC(SYSDATE) AND TRUNC(SYSDATE) + 7;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'Q4', 'BASIC +COST +PREDICATE'));

-- Q5: productos con mas de 6 meses en bodega (usa IX_LOT_INGRESO)
EXPLAIN PLAN SET STATEMENT_ID = 'Q5' FOR
SELECT l.LOT_ID, l.LOT_FECHA_INGRESO FROM LOTE l WHERE l.LOT_FECHA_INGRESO <= ADD_MONTHS(TRUNC(SYSDATE), -6);
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'Q5', 'BASIC +COST +PREDICATE'));

-- Q6: top 10 clientes que mas compran en 6 meses (usa IX_FAC_FECHA)
EXPLAIN PLAN SET STATEMENT_ID = 'Q6' FOR
SELECT CLI_ID, SUM(FAC_TOTAL) TOTAL FROM FACTURA
 WHERE FAC_ESTADO IN ('PENDIENTE', 'CANCELADA') AND FAC_FECHA >= ADD_MONTHS(TRUNC(SYSDATE), -6)
 GROUP BY CLI_ID ORDER BY TOTAL DESC FETCH FIRST 10 ROWS ONLY;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'Q6', 'BASIC +COST +PREDICATE'));

-- Q7: cierre diario (facturas de un dia, usa IX_FAC_FECHA)
EXPLAIN PLAN SET STATEMENT_ID = 'Q7' FOR
SELECT f.USR_ID, SUM(f.FAC_TOTAL) FROM FACTURA f
 WHERE f.FAC_FECHA >= TRUNC(SYSDATE) AND f.FAC_FECHA < TRUNC(SYSDATE) + 1 AND f.FAC_ESTADO <> 'ANULADA' GROUP BY f.USR_ID;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'Q7', 'BASIC +COST +PREDICATE'));

-- Q8: ultimo pago de un cliente (usa IX_ABC_FECHA / IX_CXC_CLI)
EXPLAIN PLAN SET STATEMENT_ID = 'Q8' FOR
SELECT MAX(a.ABC_FECHA) FROM CXC_ABONO a JOIN CUENTA_POR_COBRAR x ON x.CXC_ID = a.CXC_ID WHERE x.CLI_ID = 5;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'Q8', 'BASIC +COST +PREDICATE'));

-- Q9: precio vigente de un producto por negocio (usa UX_HIS_VIGENTE / UQ_HIS_PRD_NEG_DESDE)
EXPLAIN PLAN SET STATEMENT_ID = 'Q9' FOR
SELECT * FROM HISTORICO_PRECIO WHERE PRD_ID = 1 AND NEG_ID = 1 AND HIS_FECHA_HASTA IS NULL;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'Q9', 'BASIC +COST +PREDICATE'));

-- Q10: busqueda en el padron por cedula (usa UQ_PAD_CEDULA)
EXPLAIN PLAN SET STATEMENT_ID = 'Q10' FOR
SELECT * FROM PADRON_NACIONAL WHERE PAD_CEDULA = '105870456';
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'Q10', 'BASIC +COST +PREDICATE'));

-- Q11: facturas pendientes de cobro (usa IX_FAC_ESTADO)
EXPLAIN PLAN SET STATEMENT_ID = 'Q11' FOR
SELECT FAC_ID, CLI_ID, FAC_TOTAL FROM FACTURA WHERE FAC_ESTADO = 'PENDIENTE' AND FAC_TIPO = 'CREDITO';
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'Q11', 'BASIC +COST +PREDICATE'));

-- Q12: descuento vigente de un lote al facturar (usa IX_DSP_LOT)
EXPLAIN PLAN SET STATEMENT_ID = 'Q12' FOR
SELECT NVL(MAX(DSP_PORCENTAJE), 0) FROM DESCUENTO_PRODUCTO WHERE LOT_ID = 1 AND DSP_ESTADO = 'A';
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'Q12', 'BASIC +COST +PREDICATE'));
