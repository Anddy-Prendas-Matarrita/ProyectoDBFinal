/* ============================================================================
   ENTREGABLE #2 - PARTE A - 12_vistas_materializadas.sql
   * MV_VENTAS_MENSUALES      ventas por mes y sucursal
   * MV_INVENTARIO_CONSOLIDADO existencias por producto (central + sucursales) valoradas a costo
   * VW_ACCIONES_CLIENTE      acciones de promociones por cliente (resultado de PKG_PROMOCIONES)
   * PKG_REPORTES.P_REFRESCAR_MV  refresca ambas (lo invoca un job; REFRESH COMPLETE ON DEMAND)
   Requiere el privilegio CREATE MATERIALIZED VIEW (00_prerequisitos_DBA.sql).
   ============================================================================ */
ALTER SESSION SET CURRENT_SCHEMA = SUM_ADMIN;

CREATE MATERIALIZED VIEW MV_VENTAS_MENSUALES
    TABLESPACE TS_SUM_DATOS
    BUILD IMMEDIATE
    REFRESH COMPLETE ON DEMAND
AS
SELECT TRUNC(f.FAC_FECHA, 'MM')   AS MES,
       f.SUC_ID,
       s.SUC_NOMBRE,
       COUNT(*)                   AS CANT_FACTURAS,
       SUM(f.FAC_SUBTOTAL)        AS SUBTOTAL,
       SUM(f.FAC_DESCUENTO)       AS DESCUENTOS,
       SUM(f.FAC_IMPUESTO)        AS IMPUESTOS,
       SUM(f.FAC_TOTAL)           AS TOTAL_VENDIDO
  FROM FACTURA f
  JOIN SUCURSAL s ON s.SUC_ID = f.SUC_ID
 WHERE f.FAC_ESTADO IN ('PENDIENTE', 'CANCELADA')
 GROUP BY TRUNC(f.FAC_FECHA, 'MM'), f.SUC_ID, s.SUC_NOMBRE;
COMMENT ON MATERIALIZED VIEW MV_VENTAS_MENSUALES IS 'Ventas mensuales por sucursal (facturas pendientes o canceladas). Refresco completo bajo demanda.';

CREATE MATERIALIZED VIEW MV_INVENTARIO_CONSOLIDADO
    TABLESPACE TS_SUM_DATOS
    BUILD IMMEDIATE
    REFRESH COMPLETE ON DEMAND
AS
SELECT p.PRD_ID, p.PRD_CODIGO, p.PRD_NOMBRE, fa.FAM_NOMBRE,
       NVL(c.CANT, 0)                        AS CANT_CENTRAL,
       NVL(s.CANT, 0)                        AS CANT_SUCURSALES,
       NVL(c.CANT, 0) + NVL(s.CANT, 0)       AS CANT_TOTAL,
       p.PRD_PRECIO_COSTO,
       (NVL(c.CANT, 0) + NVL(s.CANT, 0)) * p.PRD_PRECIO_COSTO AS VALOR_COSTO
  FROM PRODUCTO p
  JOIN FAMILIA_PRODUCTO fa ON fa.FAM_ID = p.FAM_ID
  LEFT JOIN (SELECT l.PRD_ID, SUM(i.INC_CANTIDAD) CANT FROM INVENTARIO_CENTRAL i JOIN LOTE l ON l.LOT_ID = i.LOT_ID GROUP BY l.PRD_ID) c ON c.PRD_ID = p.PRD_ID
  LEFT JOIN (SELECT l.PRD_ID, SUM(i.INS_CANTIDAD) CANT FROM INVENTARIO_SUCURSAL i JOIN LOTE l ON l.LOT_ID = i.LOT_ID GROUP BY l.PRD_ID) s ON s.PRD_ID = p.PRD_ID;
COMMENT ON MATERIALIZED VIEW MV_INVENTARIO_CONSOLIDADO IS 'Inventario consolidado por producto: bodega central, sucursales, total y valor a costo.';

CREATE INDEX IX_MVI_PRD ON MV_INVENTARIO_CONSOLIDADO (PRD_ID) TABLESPACE TS_SUM_INDICES;
CREATE INDEX IX_MVV_MES ON MV_VENTAS_MENSUALES (MES) TABLESPACE TS_SUM_INDICES;

CREATE OR REPLACE VIEW VW_ACCIONES_CLIENTE AS
SELECT c.CLI_ID, c.CLI_NOMBRE || ' ' || NVL(c.CLI_APELLIDO1, '') AS CLIENTE,
       pm.PRM_ID, pm.PRM_NOMBRE, tp.TPR_UNIDAD_PREMIO,
       SUM(x.PMC_CANT_PATROCINADORES) AS CANT_PATROCINADORES,
       SUM(x.PMC_ACCIONES)            AS ACCIONES_OTORGADAS
  FROM PROMOCION_CLIENTE x
  JOIN CLIENTE c ON c.CLI_ID = x.CLI_ID
  JOIN PROMOCION pm ON pm.PRM_ID = x.PRM_ID
  JOIN TIPO_PROMOCION tp ON tp.TPR_ID = pm.TPR_ID
 GROUP BY c.CLI_ID, c.CLI_NOMBRE, c.CLI_APELLIDO1, pm.PRM_ID, pm.PRM_NOMBRE, tp.TPR_UNIDAD_PREMIO;
COMMENT ON TABLE VW_ACCIONES_CLIENTE IS 'Acciones (o unidades) de promocion que corresponde otorgar a cada cliente.';

CREATE OR REPLACE PACKAGE PKG_REPORTES AS
    PROCEDURE P_REFRESCAR_MV;
END PKG_REPORTES;
/
CREATE OR REPLACE PACKAGE BODY PKG_REPORTES AS
    PROCEDURE P_REFRESCAR_MV IS
        v_prl NUMBER;
    BEGIN
        v_prl := PKG_PROCESOS.F_INICIAR('PKG_REPORTES.P_REFRESCAR_MV');
        DBMS_MVIEW.REFRESH('MV_VENTAS_MENSUALES', 'C');
        DBMS_MVIEW.REFRESH('MV_INVENTARIO_CONSOLIDADO', 'C');
        PKG_PROCESOS.P_FINALIZAR(v_prl, 'OK', 'Vistas materializadas refrescadas');
    EXCEPTION
        WHEN OTHERS THEN
            PKG_ERRORES.P_REGISTRAR('PKG_REPORTES', 'P_REFRESCAR_MV', SQLCODE, SQLERRM);
            IF v_prl IS NOT NULL THEN PKG_PROCESOS.P_FINALIZAR(v_prl, 'ERROR', SQLERRM); END IF;
            RAISE;
    END P_REFRESCAR_MV;
END PKG_REPORTES;
/
