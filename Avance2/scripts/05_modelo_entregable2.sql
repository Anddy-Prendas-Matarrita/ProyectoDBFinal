         WHEN FAC_ESTADO IN ('ANULADA','DEVUELTA') THEN FAC_ESTADO
         WHEN FAC_TIPO = 'CREDITO' AND EXISTS (SELECT 1 FROM CUENTA_POR_COBRAR c
                WHERE c.FAC_ID = f.FAC_ID AND c.CXC_ESTADO IN ('PENDIENTE','PARCIAL')) THEN 'PENDIENTE'
         ELSE 'CANCELADA' END;
ALTER TABLE FACTURA ADD CONSTRAINT CK_FAC_ESTADO
    CHECK (FAC_ESTADO IN ('PENDIENTE','CANCELADA','ANULADA','DEVUELTA'));
ALTER TABLE FACTURA ADD CONSTRAINT CK_FAC_TIPO_ESTADO
    CHECK (NOT (FAC_TIPO = 'CONTADO' AND FAC_ESTADO = 'PENDIENTE'));

-- 3.3 Calculo inicial de los saldos a partir de las cuentas existentes
UPDATE CLIENTE c SET CLI_SALDO_ACTUAL = NVL((SELECT SUM(x.CXC_SALDO) FROM CUENTA_POR_COBRAR x
        WHERE x.CLI_ID = c.CLI_ID AND x.CXC_ESTADO IN ('PENDIENTE','PARCIAL')), 0);
UPDATE PROVEEDOR p SET PRV_SALDO_ACTUAL = NVL((SELECT SUM(x.CXP_SALDO) FROM CUENTA_POR_PAGAR x
        WHERE x.PRV_ID = p.PRV_ID AND x.CXP_ESTADO IN ('PENDIENTE','PARCIAL')), 0);

-- 3.4 Restricciones sobre los saldos (el saldo nunca supera el limite de credito)
ALTER TABLE CLIENTE   ADD CONSTRAINT CK_CLI_SALDO CHECK (CLI_SALDO_ACTUAL >= 0 AND CLI_SALDO_ACTUAL <= CLI_LIMITE_CREDITO);
ALTER TABLE PROVEEDOR ADD CONSTRAINT CK_PRV_SALDO CHECK (PRV_SALDO_ACTUAL >= 0 AND PRV_SALDO_ACTUAL <= PRV_LIMITE_CREDITO);

