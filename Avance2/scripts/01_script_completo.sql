/* Formula de precios (ver VW_PRECIO_VENTA y la documentacion tecnica):
   1) Precio base  = costo x (1 + utilidad% del negocio)
   2) Precio neto  = precio base x (1 - descuento%)      [descuento <= maximo permitido]
   3) Precio final = precio neto x (1 + tasa de impuesto%) [0% si el producto es exento]
   Cada cambio de costo o de utilidad cierra el registro vigente en HISTORICO_PRECIO
   y abre uno nuevo (un unico registro vigente por producto y negocio). */

CREATE OR REPLACE VIEW VW_STOCK_SUCURSAL AS
SELECT s.SUC_ID, s.SUC_NOMBRE, p.PRD_ID, p.PRD_CODIGO, p.PRD_NOMBRE, f.FAM_NOMBRE,
       l.LOT_ID, l.LOT_NUMERO, l.LOT_FECHA_VENCIMIENTO,
       i.INS_CANTIDAD AS CANTIDAD_DISPONIBLE
FROM INVENTARIO_SUCURSAL i
JOIN SUCURSAL s ON s.SUC_ID = i.SUC_ID
JOIN LOTE l ON l.LOT_ID = i.LOT_ID
JOIN PRODUCTO p ON p.PRD_ID = l.PRD_ID
JOIN FAMILIA_PRODUCTO f ON f.FAM_ID = p.FAM_ID;

CREATE OR REPLACE VIEW VW_LOTES_VIGENCIA AS
SELECT l.LOT_ID, l.LOT_NUMERO, p.PRD_ID, p.PRD_CODIGO, p.PRD_NOMBRE,
       l.LOT_FECHA_INGRESO, l.LOT_FECHA_VENCIMIENTO,
       TRUNC(SYSDATE) - l.LOT_FECHA_INGRESO AS DIAS_ANTIGUEDAD,
       CASE WHEN l.LOT_FECHA_VENCIMIENTO IS NULL THEN NULL
            ELSE l.LOT_FECHA_VENCIMIENTO - TRUNC(SYSDATE) END AS DIAS_PARA_VENCER,
       NVL(c.INC_CANTIDAD, 0) AS CANTIDAD_CENTRAL
FROM LOTE l
JOIN PRODUCTO p ON p.PRD_ID = l.PRD_ID
LEFT JOIN INVENTARIO_CENTRAL c ON c.LOT_ID = l.LOT_ID;

CREATE OR REPLACE VIEW VW_PRECIO_VENTA AS
SELECT x.PRD_ID, x.PRD_CODIGO, x.PRD_NOMBRE, x.NEG_ID, x.PRD_PRECIO_COSTO,
       x.PRN_PORC_UTILIDAD, x.PRECIO_BASE, x.TASA_IMPUESTO, x.PORC_DESCUENTO,
       ROUND(x.PRECIO_BASE * (1 + x.TASA_IMPUESTO / 100), 2) AS PRECIO_VENTA_SIN_DESCUENTO,
       ROUND(x.PRECIO_BASE * (1 - x.PORC_DESCUENTO / 100) * (1 + x.TASA_IMPUESTO / 100), 2) AS PRECIO_VENTA_FINAL
FROM (
  SELECT p.PRD_ID, p.PRD_CODIGO, p.PRD_NOMBRE, pn.NEG_ID, p.PRD_PRECIO_COSTO,
         pn.PRN_PORC_UTILIDAD,
         ROUND(p.PRD_PRECIO_COSTO * (1 + pn.PRN_PORC_UTILIDAD / 100), 2) AS PRECIO_BASE,
         NVL(i.IMP_TASA, 0) AS TASA_IMPUESTO,
         LEAST(pn.PRN_PORC_DESC_MAX,
               NVL((SELECT MAX(d.DES_PORCENTAJE)
                      FROM DESCUENTO d
                     WHERE d.DES_ESTADO = 'A'
                       AND TRUNC(SYSDATE) BETWEEN d.DES_FECHA_INICIO AND d.DES_FECHA_FIN
                       AND ((d.DES_TIPO = 'FAMILIA' AND d.FAM_ID = p.FAM_ID)
                         OR (d.DES_TIPO = 'PROVEEDOR' AND d.PRV_ID = p.PRV_ID))), 0)) AS PORC_DESCUENTO
  FROM PRODUCTO p
  JOIN PRODUCTO_NEGOCIO pn ON pn.PRD_ID = p.PRD_ID
  LEFT JOIN IMPUESTO i ON i.IMP_ID = p.IMP_ID
  WHERE p.PRD_ESTADO = 'A'
) x;

CREATE OR REPLACE VIEW VW_FACTURAS_DETALLE AS
SELECT fa.FAC_ID, fa.FAC_NUMERO, fa.FAC_FECHA, fa.FAC_TIPO,
       c.CLI_NOMBRE || ' ' || NVL(c.CLI_APELLIDO1, '') AS CLIENTE,
       su.SUC_NOMBRE, u.USR_NOMBRE,
       fa.FAC_SUBTOTAL, fa.FAC_DESCUENTO, fa.FAC_IMPUESTO, fa.FAC_TOTAL, fa.FAC_ESTADO
FROM FACTURA fa
JOIN CLIENTE c ON c.CLI_ID = fa.CLI_ID
JOIN SUCURSAL su ON su.SUC_ID = fa.SUC_ID
JOIN USUARIO u ON u.USR_ID = fa.USR_ID;

CREATE OR REPLACE VIEW VW_CXP_PENDIENTES AS
SELECT cp.CXP_ID, pr.PRV_RAZON_SOCIAL, cp.CXP_NUMERO_FACTURA, cp.CXP_FECHA,
       cp.CXP_FECHA_VENCIMIENTO, cp.CXP_MONTO_TOTAL, cp.CXP_SALDO, cp.CXP_ESTADO
FROM CUENTA_POR_PAGAR cp
JOIN PROVEEDOR pr ON pr.PRV_ID = cp.PRV_ID
WHERE cp.CXP_SALDO > 0 AND cp.CXP_ESTADO <> 'ANULADA';

CREATE OR REPLACE VIEW VW_CXC_PENDIENTES AS
SELECT cc.CXC_ID, c.CLI_NOMBRE || ' ' || NVL(c.CLI_APELLIDO1, '') AS CLIENTE,
       fa.FAC_NUMERO, cc.CXC_FECHA_VENCIMIENTO, cc.CXC_MONTO, cc.CXC_SALDO, cc.CXC_ESTADO
