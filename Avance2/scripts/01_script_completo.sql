/* ============================================================================
   1. TABLESPACES (minimo 3: datos, indices y auditoria/bitacoras)
   ============================================================================ */
CREATE TABLESPACE TS_SUM_DATOS
    DATAFILE 'ts_sum_datos01.dbf' SIZE 200M
    AUTOEXTEND ON NEXT 50M MAXSIZE 2048M
    EXTENT MANAGEMENT LOCAL AUTOALLOCATE
    SEGMENT SPACE MANAGEMENT AUTO;

CREATE TABLESPACE TS_SUM_INDICES
    DATAFILE 'ts_sum_indices01.dbf' SIZE 100M
    AUTOEXTEND ON NEXT 50M MAXSIZE 1024M
    EXTENT MANAGEMENT LOCAL AUTOALLOCATE
    SEGMENT SPACE MANAGEMENT AUTO;

CREATE TABLESPACE TS_SUM_AUDITORIA
    DATAFILE 'ts_sum_auditoria01.dbf' SIZE 50M
    AUTOEXTEND ON NEXT 20M MAXSIZE 512M
    EXTENT MANAGEMENT LOCAL AUTOALLOCATE
    SEGMENT SPACE MANAGEMENT AUTO;

/* ============================================================================
   2. USUARIO PROPIETARIO DEL ESQUEMA
   ============================================================================ */
CREATE USER SUM_ADMIN IDENTIFIED BY "Suministros2026#"
    DEFAULT TABLESPACE TS_SUM_DATOS
    TEMPORARY TABLESPACE TEMP
    QUOTA UNLIMITED ON TS_SUM_DATOS
    QUOTA UNLIMITED ON TS_SUM_INDICES
    QUOTA UNLIMITED ON TS_SUM_AUDITORIA;

GRANT CONNECT, RESOURCE TO SUM_ADMIN;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW,
      CREATE TRIGGER, CREATE PROCEDURE TO SUM_ADMIN;

-- A partir de aqui todos los objetos se crean en el esquema SUM_ADMIN
ALTER SESSION SET CURRENT_SCHEMA = SUM_ADMIN;

