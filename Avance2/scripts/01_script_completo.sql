CREATE OR REPLACE VIEW VW_CREDITO_PROVEEDOR AS
SELECT pr.PRV_ID, pr.PRV_RAZON_SOCIAL, pr.PRV_LIMITE_CREDITO,
       NVL(SUM(cp.CXP_SALDO), 0) AS SALDO_UTILIZADO,
       pr.PRV_LIMITE_CREDITO - NVL(SUM(cp.CXP_SALDO), 0) AS CREDITO_DISPONIBLE
FROM PROVEEDOR pr
LEFT JOIN CUENTA_POR_PAGAR cp ON cp.PRV_ID = pr.PRV_ID AND cp.CXP_ESTADO IN ('PENDIENTE','PARCIAL')
GROUP BY pr.PRV_ID, pr.PRV_RAZON_SOCIAL, pr.PRV_LIMITE_CREDITO;

CREATE OR REPLACE VIEW VW_CREDITO_CLIENTE AS
SELECT c.CLI_ID, c.CLI_NOMBRE || ' ' || NVL(c.CLI_APELLIDO1, '') AS CLIENTE, c.CLI_LIMITE_CREDITO,
       NVL(SUM(cc.CXC_SALDO), 0) AS SALDO_UTILIZADO,
       c.CLI_LIMITE_CREDITO - NVL(SUM(cc.CXC_SALDO), 0) AS CREDITO_DISPONIBLE
FROM CLIENTE c
LEFT JOIN CUENTA_POR_COBRAR cc ON cc.CLI_ID = c.CLI_ID AND cc.CXC_ESTADO IN ('PENDIENTE','PARCIAL')
WHERE c.CLI_PREFERENCIAL = 'S'
GROUP BY c.CLI_ID, c.CLI_NOMBRE, c.CLI_APELLIDO1, c.CLI_LIMITE_CREDITO;

